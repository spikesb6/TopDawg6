// Builds supabase/seed.sql from src/data/seed-ideas.json so ids match the app's local data.
// Run with `npm run gen:seed`.
const fs = require('fs');
const path = require('path');

const quote = (value) => (value == null ? 'null' : `'${String(value).replace(/'/g, "''")}'`);

function buildSeedSql(ideas) {
  const rows = ideas.map(
    (i) =>
      `  (${i.id}, ${quote(i.mode)}, ${quote(i.name)}, ${quote(i.blurb)}, ${quote(i.mood)}, ${i.cost}, ${i.minutes ?? 'null'}, ${quote(i.details)})`
  );
  return `-- Generated by scripts/gen-seed.js from src/data/seed-ideas.json. Do not edit by hand.

insert into public.ideas (id, mode, name, blurb, mood, cost, minutes, details)
overriding system value
values
${rows.join(',\n')}
on conflict (id) do update set
  mode = excluded.mode,
  name = excluded.name,
  blurb = excluded.blurb,
  mood = excluded.mood,
  cost = excluded.cost,
  minutes = excluded.minutes,
  details = excluded.details;

select setval(pg_get_serial_sequence('public.ideas', 'id'), (select max(id) from public.ideas));
`;
}

module.exports = { buildSeedSql };

if (require.main === module) {
  const root = path.join(__dirname, '..');
  const ideas = JSON.parse(fs.readFileSync(path.join(root, 'src/data/seed-ideas.json'), 'utf8'));
  fs.writeFileSync(path.join(root, 'supabase/seed.sql'), buildSeedSql(ideas));
  console.log(`Wrote supabase/seed.sql with ${ideas.length} ideas`);
}
